import { writeFileSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export function releaseConfiguration(repository, publicKey) {
  if (!/^[A-Za-z0-9][A-Za-z0-9_.-]*\/[A-Za-z0-9][A-Za-z0-9_.-]*$/.test(repository ?? '')) {
    throw new Error('Set RELEASE_REPOSITORY to the public owner/repository that hosts release assets.');
  }
  const key = publicKey?.trim();
  if (!key || !/^[A-Za-z0-9+/]+={0,2}$/.test(key)) throw new Error('Set TAURI_UPDATER_PUBLIC_KEY to the public key generated by the Tauri signer.');
  const decoded = Buffer.from(key, 'base64').toString('utf8');
  if (!/^untrusted comment: .+\r?\n[A-Za-z0-9+/]+={0,2}\r?\n?$/.test(decoded)) throw new Error('The updater public key must contain an encoded minisign public key.');
  const rawKey = Buffer.from(decoded.trim().split(/\r?\n/)[1], 'base64');
  if (rawKey.length !== 42 || rawKey.subarray(0, 2).toString('ascii') !== 'Ed') throw new Error('Invalid minisign public key.');
  return {
    bundle: { createUpdaterArtifacts: true },
    plugins: { updater: { pubkey: key, endpoints: [`https://github.com/${repository}/releases/latest/download/latest.json`] } },
  };
}
export function validateReleaseVersion(tag, root = process.cwd()) {
  const pkg = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8'));
  const config = JSON.parse(readFileSync(resolve(root, 'src-tauri/tauri.conf.json'), 'utf8'));
  const cargo = readFileSync(resolve(root, 'src-tauri/Cargo.toml'), 'utf8').match(/^version\s*=\s*"([^"]+)"/m)?.[1];
  if (!/^v\d+\.\d+\.\d+$/.test(tag ?? '') || tag !== `v${pkg.version}` || config.version !== pkg.version || cargo !== pkg.version) {
    throw new Error('The stable vX.Y.Z release tag must match package.json, Cargo.toml, and tauri.conf.json.');
  }
}
if (import.meta.url.startsWith('file:') && process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.env.RELEASE_TAG) validateReleaseVersion(process.env.RELEASE_TAG);
  const config = releaseConfiguration(process.env.RELEASE_REPOSITORY, process.env.TAURI_UPDATER_PUBLIC_KEY);
  const output = resolve('src-tauri/tauri.updater.generated.json');
  writeFileSync(output, JSON.stringify(config, null, 2) + '\n');
  console.log(`Prepared signed updater build for ${process.env.RELEASE_REPOSITORY}.`);
}
